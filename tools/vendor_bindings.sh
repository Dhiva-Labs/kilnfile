#!/usr/bin/env bash
# Assembles the umbrella Rust crate `kilnfile_rs` and the patched C++ wrapper
# sources in an output directory, leaving third_party/safe-bindings pristine.
#
# Every safe-bindings binding crate is named `rust`, so its Crubit C++ API lands
# in `rust::` and each one wants to be its own staticlib. This script instead:
#   * copies each binding's Rust sources as a module of one crate
#     (zip -> sb_zip, xml -> sb_xml) and kilnfile's own bridge as
#     `kilnfile_bridge`, rewriting `crate::` paths;
#   * merges their [dependencies] into one Cargo.toml;
#   * copies each binding's C++ wrappers and rewrites `rust::` to
#     `kilnfile_rs::<module>::` and `crubit/rust.h` to `crubit/kilnfile_rs.h`.
#
# Usage: tools/vendor_bindings.sh <out_dir>
# Output: <out_dir>/kilnfile_rs/   (Cargo crate, umbrella)
#         <out_dir>/cpp/<zip|xml>/ (patched wrappers)
#         <out_dir>/cpp/crubit_helpers/
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
sb="${root}/third_party/safe-bindings"
out="${1:?usage: vendor_bindings.sh <out_dir>}"
crate="kilnfile_rs"
# binding dir -> module name
declare -A mods=([zip]=sb_zip [xml]=sb_xml)

[[ -f "${sb}/zip/rust/lib.rs" ]] || { echo "safe-bindings submodule missing" >&2; exit 1; }

rm -rf "${out}/${crate}" "${out}/cpp"
mkdir -p "${out}/${crate}/src" "${out}/cpp"

# Rewrites the Rust sources of one crate into a module directory.
vendor_rust() { # <src_dir> <module> <root_file>
  local src="$1" mod="$2" rootfile="$3" dst="${out}/${crate}/src/$2"
  mkdir -p "${dst}"
  for f in "${src}"/*.rs; do
    local name; name="$(basename "${f}")"
    [[ "${name}" == "${rootfile}" ]] && name="mod.rs"
    perl -pe "s/\\bcrate::/crate::${mod}::/g" "${f}" > "${dst}/${name}"
  done
}

# Dependencies section (until the next table) of a Cargo.toml.
deps_of() { awk '/^\[dependencies\]/{on=1;next} /^\[/{on=0} on' "$1"; }

vendor_rust "${root}/bridge/src" kilnfile_bridge lib.rs
vendor_rust "${sb}/zip/rust" sb_zip lib.rs
vendor_rust "${sb}/xml/rust" sb_xml lib.rs

cat > "${out}/${crate}/src/lib.rs" <<LIB
//! Generated by tools/vendor_bindings.sh. Do not edit.
//! One crate, one staticlib, one Crubit header for every Rust piece of kilnfile.
pub mod kilnfile_bridge;
pub mod sb_zip;
pub mod sb_xml;
LIB

{
  cat <<TOML
[package]
name = "${crate}"
version = "0.1.0"
edition = "2024"
license = "Apache-2.0"

[lib]
path = "src/lib.rs"
doctest = false

[dependencies]
TOML
  deps_of "${root}/bridge/Cargo.toml"
  deps_of "${sb}/zip/rust/Cargo.toml"
  deps_of "${sb}/xml/rust/Cargo.toml"
} | awk 'NF || !blank {print} {blank = !NF}' > "${out}/${crate}/Cargo.toml"

# Patched C++ wrappers.
mkdir -p "${out}/cpp/crubit_helpers"
cp "${sb}/crubit_helpers/"*.h "${out}/cpp/crubit_helpers/"
for b in "${!mods[@]}"; do
  mod="${mods[${b}]}"
  mkdir -p "${out}/cpp/${b}"
  for f in "${sb}/${b}"/*.h "${sb}/${b}"/*.cc; do
    name="$(basename "${f}")"
    [[ "${name}" == "main.cc" ]] && continue  # upstream example programs
    perl -pe "s{crubit/rust\\.h}{crubit/${crate}.h}g; s/(?<![\\w:])(?:::)?rust::/::${crate}::${mod}::/g" \
      "${f}" > "${out}/cpp/${b}/${name}"
  done
done
echo "vendored into ${out}"
